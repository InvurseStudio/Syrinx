"""Writes crates/syrinx-engine/src/tokenizer/unicode_tables.rs: the code point ranges of
Unicode's letters (general category L), marks (M) and numbers (N), which the
tokenizer's pre-tokenizers split text by. With --case, writes unicode_case_tables.rs
instead: the uppercase and titlecase letters (Lu, Lt) and the lowercase ones (Ll), for
the Llama 4 pre-tokenizer.

Uses Python's own Unicode database, so nothing is downloaded. Run it again with a newer
Python to move to a newer Unicode version:

    python -I tools/gen_unicode_tables.py
    python -I tools/gen_unicode_tables.py --case

The case tables may come from an older Unicode than the main ones (they were first made
with Python 3.11's Unicode 14): a letter added since counts as caseless, both upper and
lower for the Llama 4 split.
"""

import pathlib
import sys
import unicodedata

HERE = pathlib.Path(__file__).resolve().parent.parent / "crates/syrinx-engine/src/tokenizer"
OUT = HERE / "unicode_tables.rs"
CASE_OUT = HERE / "unicode_case_tables.rs"


def ranges(category_prefix):
    """Inclusive (first, last) ranges of code points whose category starts with the prefix
    (or is one of a tuple of categories)."""
    found = []
    start = None
    for cp in range(sys.maxunicode + 2):
        inside = cp <= sys.maxunicode and unicodedata.category(chr(cp)).startswith(category_prefix)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            found.append((start, cp - 1))
            start = None
    return found


def table(name, doc, found):
    lines = [f"/// {doc}", f"pub(super) const {name}: &[(u32, u32)] = &["]
    row = []
    for first, last in found:
        row.append(f"(0x{first:X}, 0x{last:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    letters = ranges("L")
    marks = ranges("M")
    numbers = ranges("N")
    text = "\n\n".join([
        "// Generated by tools/gen_unicode_tables.py from Unicode "
        f"{unicodedata.unidata_version}. Don't edit by hand.\n"
        "// Inclusive code point ranges, sorted, for binary search.",
        "/// The Unicode version these tables come from.\n"
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        table("LETTERS", "General category L: Lu, Ll, Lt, Lm, Lo.", letters),
        table("MARKS", "General category M: Mn, Mc, Me.", marks),
        table("NUMBERS", "General category N: Nd, Nl, No.", numbers),
    ]) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Unicode {unicodedata.unidata_version}: {len(letters)} letter ranges, "
          f"{len(marks)} mark ranges, {len(numbers)} number ranges -> {OUT}")


def main_case():
    upper = ranges(("Lu", "Lt"))
    lower = ranges("Ll")
    text = "\n\n".join([
        "// Generated by tools/gen_unicode_tables.py --case from Unicode "
        f"{unicodedata.unidata_version}. Don't edit by hand.\n"
        "// Inclusive code point ranges, sorted, for binary search.",
        "/// The Unicode version these tables come from.\n"
        f'pub const CASE_UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        table("UPPER", "General categories Lu and Lt.", upper),
        table("LOWER", "General category Ll.", lower),
    ]) + "\n"
    CASE_OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Unicode {unicodedata.unidata_version}: {len(upper)} upper ranges, "
          f"{len(lower)} lower ranges -> {CASE_OUT}")


if __name__ == "__main__":
    if sys.argv[1:] == ["--case"]:
        main_case()
    else:
        main()
